export const STRINGS = { en, de };
const stored = (() => {
  try {
    return localStorage.getItem("lang");
  } catch {
    return null;
  }
})();
export const lang = signal<"en" | "de">(stored === "de" || stored === "en" ? stored : typeof navigator !== "undefined" && navigator.language.startsWith("de") ? "de" : "en");
export const t = (k: Key): string => STRINGS[lang.value][k];
export function toggleLang() {
  lang.value = lang.value === "en" ? "de" : "en";
  try {
    localStorage.setItem("lang", lang.value);
  } catch {
    /* private mode: the choice lasts for this page */
  }
  document.documentElement.lang = lang.value;
}
